def poner_idioma(idioma: str) -> None:
    global _idioma
    _idioma = idioma if idioma in TEXTOS else "es"


def idioma() -> str:
    return _idioma


def t(clave: str, **valores) -> str:
    texto = TEXTOS[_idioma].get(clave) or TEXTOS["es"].get(clave) or clave
    return texto.format(**valores) if valores else texto
